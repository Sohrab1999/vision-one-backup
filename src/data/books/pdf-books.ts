/** پیکربندی PDF یک کتاب — فقط برای کتاب‌های kind:"pdf" مقدار دارد */
export function getPdfBookConfig(id: BookId): PdfBookConfig | undefined {
  return PDF_BOOKS[id];
}

/** شمارهٔ داستانِ یک صفحه (۰ یعنی جلد/مقدمه) */
export function storyAtPage(cfg: PdfBookConfig, pdfPage: number): number {
  let story = 0;
  for (let i = 0; i < cfg.storyPages.length; i++) {
    if (cfg.storyPages[i] <= pdfPage) story = i + 1;
  }
  return story;
}
