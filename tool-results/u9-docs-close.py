import io, sys

def patch(path, repls, name):
    with io.open(path, "r", encoding="utf-8") as f:
        src = f.read()
    misses = []
    for old, new in repls:
        if old in src:
            src = src.replace(old, new, 1)
        else:
            misses.append(old[:60])
    with io.open(path, "w", encoding="utf-8") as f:
        f.write(src)
    if misses:
        print(f"{name}: MISSED -> {misses}")
        sys.exit(1)
    print(f"{name}: OK ({len(repls)} edits)")

