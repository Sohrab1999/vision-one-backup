/** برش ۱-ایندکس‌شدهٔ inclusive + dedent اختیاری (حذف n فاصلهٔ اول هر خط) */
const seg = (a: number, b: number, dedent = 0): string =>
  L.slice(a - 1, b)
    .map((l) => (dedent > 0 ? l.replace(new RegExp(`^ {${dedent}}`), "") : l))
    .join("\n");

/** افزودن export به اعلان‌های سطح بالا (فقط دلتای مجاز) */
const exportAdd = (s: string, kinds: "decl" | "fn"): string =>
  s
    .split("\n")
    .map((l) =>
      kinds === "decl"
        ? l.replace(/^(type|const|interface) /, "export $1 ")
        : l.replace(/^function /, "export function "),
    )
    .join("\n");

