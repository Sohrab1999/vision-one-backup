"""Phase 3G-2 — exact-once line-level edits for phase-3 doc + mother doc.
Method: locate the UNIQUE line containing a verified anchor; keep the criterion
text before '←' verbatim; swap tick and margin. Assert exactly one match."""
import io, sys

def load(p):
    with io.open(p, 'r', encoding='utf-8') as f:
        return f.read()

def save(p, s):
    with io.open(p, 'w', encoding='utf-8') as f:
        f.write(s)

def replace_line(content, anchor, new_margin, tick, tag):
    lines = content.split('\n')
    idx = [i for i, l in enumerate(lines) if anchor in l]
    assert len(idx) == 1, "%s: anchor matched %d lines (expected 1)" % (tag, len(idx))
    i = idx[0]
    old = lines[i]
    sep = old.find('← **')
    assert sep != -1, "%s: margin separator not found" % tag
    head = old[:sep]
    if tick:
        assert head.startswith('- [ ]'), "%s: expected '- [ ]' tick" % tag
        head = '- [x]' + head[4:]
    new = head + new_margin
    lines[i] = new
    print("%s: line %d replaced OK (old %d chars -> new %d chars)" % (tag, i + 1, len(old), len(new)))
    return '\n'.join(lines)

def replace_sub(content, old_sub, new_sub, tag):
    c = content.count(old_sub)
    assert c == 1, "%s: substring count=%d (expected 1)" % (tag, c)
    print("%s: substring replaced OK" % tag)
    return content.replace(old_sub, new_sub, 1)

